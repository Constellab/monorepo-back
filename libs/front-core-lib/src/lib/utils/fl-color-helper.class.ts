  /**
   * return hexa color base generated by string with #
   */
  public static stringToRGBColor(str: string): string {
    return '#' + FlColorHelper.stringToRGB(str);
  }

  /**
   * return hexa color base generated by string
   */
  public static stringToRGB(str: string): string {
    return FlColorHelper.intToRGB(FlColorHelper.hashCode(str));
  }

  /**
   * return hexa color base generated by int
   */
  public static intToRGB(i: number): string {
    const c = (i & 0x00FFFFFF)
      .toString(16)
      .toUpperCase();

    return '00000'.substring(0, 6 - c.length) + c;
  }

  // get hash form string
  private static hashCode(str: string): number {
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
      hash = str.charCodeAt(i) + ((hash << 5) - hash);
    }
    return hash;
  }

  // return a list of colors
  public static getColorList(transparencyAlpha: number = 1): string[] {

    const colorList: string[] = [this.blue, this.pinkShiny, this.green, this.yellow,
      this.purple, this.lightBlue, this.palePink, this.paleGreen,
      this.orange, this.pink, this.brown, this.blueGreen, this.darkBlue,
      this.red, this.darkGreen, this.beige, this.lightGreen, this.mallow, this.greenShiny,
      this.grey, this.blueGrey, this.palePurple];
    if (transparencyAlpha === 1) {
      return colorList;
    }

    // change the transparency
    const colorListWithTransparency: string[] = [];
    for (const color of colorList) {
      colorListWithTransparency.push(color.replace('1)', `${transparencyAlpha})`));
    }

    return colorListWithTransparency;
  }

  public static getColorFromIndex(index: number): string {
    const colors = FlColorHelper.getColorList();

    return colors[index % colors.length];
  }

