import {FlSearchCriteria, FlSearchOperator} from './fl-search.class';
import {DateTime} from 'luxon';
import {ClDateHelper, ClHelpService, ClLuxonDateTimeTransform} from '@monorepo/core-lib';
import {FlEntity} from '../../../model/fl-entity.class';

/**
 * Object used to convert an object attribute to a {@link FlSearchCriteria} to perform a advanced search
 */
export interface FlSearchAttributeCriteriaConverter<T = string> {
  /**
   * Name of the column that will be used in the {@link FlSearchCriteria}. Support '.' to go deeply in objects
   */
  key: string;

  /**
   * Operation to filters the data passed to the {@link FlSearchCriteria}
   * If a {@link FlSearchOperator} is provided, the value is used directly
   * If a function is provided the function is call with the value to get different
   * {@link FlSearchOperator} based on criteria value
   */
  operator: FlSearchOperator | ((value: T) => FlSearchOperator);

  /**
   * Optional method to convert the attribute value to the value needed by the advanced search
   * For example: only returning the id of an object for the search
   *
   * If not provided the attribute value is directly used and no conversion are performed
   * @param value value to convert
   */
  convertValue?: (value: T) => any;
}

/**
 * Function to convert a search object attribute to SearchCriteria[];
 *
 * The value of the function is the object value (usually value from form),
 * IT CAN BE NULL or EMPTY
 */
export type FlSearchAttributeFunctionCriteriaConverter<T> = (value ?: T) => FlSearchCriteria[];

/**
 * Type for describing a conversion from an object of type P to a list of criteria
 *
 * Each object key should define how to convert the object to SearchCriteria
 *
 * Each value define either
 * - information to convert to SearchCriteria (Using SearchAttributeCriteriaConverter)
 * - a function to directly convert object info to SearchCriteria[] (for specific cases)
 */
export type FlSearchCriteriaConverter<T> = {
  [P in keyof T]: FlSearchAttributeCriteriaConverter<T[P]> | FlSearchAttributeFunctionCriteriaConverter<T[P]>
};

/**
 * Type for date group when using date interval to filter on same
 * date
 */
export class FlSearchDateInterval {

  @ClLuxonDateTimeTransform()
  from: DateTime;

  @ClLuxonDateTimeTransform()
  to: DateTime;
}

/**
 * Generic converter for Advanced Search
 */
export class FlSearchConverter {
  /**
   * Convert an object (usually generated by a form) to a list of {@link FlSearchCriteria}
   * to perform an advanced search.
   *
   * It loops through object attributes and convert it (if not null)
   * to a {@link FlSearchCriteria}
   * @param object object containing the filtering values
   * @param converter object used to convert objects attributes to {@link FlSearchCriteria}
   */
  public static convertObjectToSearchCriteriaList<T = any>(object: T,
                                                           converter: FlSearchCriteriaConverter<T>)
    : FlSearchCriteria[] {
    const criteria: FlSearchCriteria[] = [];
    for (const key of Object.keys(object)) {
      const fieldValue: any = object[key];


      // handle specific convert as function
      // for SearchAttributeFunctionCriteriaConverter
      if (typeof converter[key] === 'function') {
        // call the function to get the criteria
        const newCriteria: FlSearchCriteria[] = converter[key](fieldValue);
        if (newCriteria != null) {
          criteria.push(...newCriteria);
        }
        continue;
      }

      const fieldConverter: FlSearchAttributeCriteriaConverter<T> = converter[key];

      // check if the convert for this field exists
      if (fieldConverter == null) {
        console.error('The convert for the field ' + key + ' does not exists. Skipping field');
        continue;
      }

      // get the operation
      let operator: FlSearchOperator;
      // if the operation is a function, call it
      if (typeof fieldConverter.operator === 'function') {
        operator = fieldConverter.operator(fieldValue);
      } else {
        // otherwise get the operation directly
        operator = fieldConverter.operator;
      }

      // get the value
      let value: any;
      // if a convert function exists, call it
      if (fieldConverter.convertValue != null) {
        value = fieldConverter.convertValue(fieldValue);
      } else {
        // get the value directly
        value = fieldValue;
      }

      // if the converted value is null or empty, skip
      if (ClHelpService.isNullOrEmpty(value)) {
        continue;
      }

      criteria.push({
        key: fieldConverter.key,
        operator: operator as any,
        value: value
      });

    }
    return criteria;
  }


  /**
   * Simple method to return the id of a {@link FlEntity}
   * @param object entity
   */
  public static getEntityId(object: FlEntity): string {
    return object.id;
  }

  public static getCustomKey(key: string) {
    return (value ?: any): any => {
      if (value == null) {
        return null;
      }
      return value[key];
    };
  }

  /**
   * Simple method to convert a list of {@link FlEntity} to the list
   * of the ids
   * @param objects entities
   */
  public static getEntitiesId(objects: FlEntity[]): string[] {
    return objects.map(o => FlSearchConverter.getEntityId(o));
  }

  /**
   * Simple method to convert a Date to time
   * for the advanced search
   * @param date date to convert
   */
  public static convertDateToTime(date: Date): number {
    return date.getTime();
  }

  /**
   * Simple method to convert a DateTime to time
   * for the advanced search
   * @param date to convert
   */
  public static convertDateTimeToString(date: DateTime): string {
    return ClDateHelper.serializeDateTime(date);
  }

  /**
   * Simple method to convert a DateTime to time
   * for the advanced search
   * @param date to convert
   */
  public static convertDateToString(date: DateTime): string {
    return ClDateHelper.serializeDate(date);
  }


  /**
   * For advanced search, it convert a {@link FlSearchDateInterval} to SearchCriteria
   * depending on which interval is set
   * @param key column key
   */
  public static dateTimeInterval(key: string): FlSearchAttributeFunctionCriteriaConverter<FlSearchDateInterval> {
    return FlSearchConverter.convertDateInterval(key, FlSearchConverter.convertDateTimeToString);
  }

  /**
   * For advanced search, it convert a {@link FlSearchDateInterval} to SearchCriteria
   * depending on which interval is set
   * @param key column key
   */
  public static dateInterval(key: string): FlSearchAttributeFunctionCriteriaConverter<FlSearchDateInterval> {
    return FlSearchConverter.convertDateInterval(key, FlSearchConverter.convertDateToString);
  }

  private static convertDateInterval(key: string, dateConverter: (date: DateTime) => string):
    FlSearchAttributeFunctionCriteriaConverter<FlSearchDateInterval> {
    return (dates: FlSearchDateInterval): FlSearchCriteria[] => {
      let criteria: FlSearchCriteria;
      // if the 2 dates are null
      if (dates.from == null && dates.to == null) {
        return null;
      } else if (dates.to == null) {
        // if only the From date is filled
        criteria = {
          key: key,
          operator: 'GE',
          value: dateConverter(dates.from),
        };
      } else if (dates.from == null) {
        // if only the To date is filled
        criteria = {
          key: key,
          operator: 'LE',
          value: dateConverter(dates.to),
        };
      } else {
        // if both dates are filled
        criteria = {
          key: key,
          operator: 'BETWEEN',
          value: [dateConverter(dates.from), dateConverter(dates.to)],
        };
      }
      return [criteria];
    };
  }

  /**
   * It return false if the boolean is null or false and true if boolean
   * is true.
   *
   * With this, you can only filter on true values but not false values
   * @param bool value
   */
  public static convertBooleanFalse(bool: boolean | null): boolean {
    return !!bool;
  }


}

